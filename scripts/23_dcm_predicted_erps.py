"""
23_dcm_predicted_erps.py — the ERPs generated by the fitted DCMs vs the observed ERPs (173.695 x 100 mm).

Rows: frontocentral ROI (local effect) and parietal ROI (global effect), as in Figures 1–2.
  A/D  observed (solid) and model-predicted (dashed) ERPs: standard vs deviant
  B/E  observed vs predicted difference wave (LD − LS; GD − GS), with the correlation over time
  C/F  the difference wave at each model source (regional pyramidal-cell output, the signal the
       model projects to the scalp), showing which sources generate the MMN and the P3b in the model

How the waves are obtained from each participant's full DCM (dcm_02_fit.m):
  predicted channel data = H{trial} · U'   (H: model prediction in the 8 spatial modes; U: modes)
  observed  channel data = (H + R){trial} · U'  (data as the model saw them: same modes, same window)
  source output = Σ_states K{trial} · J. Amplitudes are in DCM's internal units (a.u.): SPM rescales
  the data before fitting, so only shapes and relative sizes are meaningful. The "observed" waves are
  the data as the DCM sees them — projected onto 8 modes and with the window mean removed (options.h
  = 1), which shifts slow components such as the P3b; compare shapes with Figure 1 accordingly.
LS/LD/GS/GD are averages of the two 2x2 cells that share that level (equal weights).
Window 0–600 ms (the DCM window). Group mean ± SE over participants.

Inputs : derivatives/dcm/fits/DCM_sub-*_full.mat
Outputs: figures/DCM_predicted_ERPs.pdf / .svg / .png; derivatives/dcm/predicted_erp_fit.json

Usage:  python scripts/23_dcm_predicted_erps.py
"""
from pathlib import Path
import json

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.io import loadmat

# ----------------------------------------------------------------------------- CONFIG
ROOT = Path(__file__).resolve().parents[1]
FIT_DIR = ROOT / "derivatives" / "dcm" / "fits"
FIG_DIR = ROOT / "figures"
SIZE_MM = (173.695, 100.0)
CONDS = ["LSGS", "LDGS", "LSGD", "LDGD"]                       # trial order in the DCM
LEVELS = {"LS": [0, 2], "LD": [1, 3], "GS": [0, 1], "GD": [2, 3]}
ROWS = [("local", ["Fz", "FC1", "FC2", "F1", "F2", "Cz"], ("LS", "LD"), "Frontocentral ROI", (80, 140)),
        ("global", ["Pz", "P1", "P2", "CPz", "POz", "CP1", "CP2"], ("GS", "GD"), "Parietal ROI", (300, 600))]
SRC = ["lA1", "rA1", "lSTG", "rSTG", "lIFG", "rIFG", "lIPL", "rIPL"]
SRC_COL = {"A1": "#9DB4C0", "STG": "#4C72B0", "IFG": "#DD8452", "IPL": "#55A868"}
C_STD = "0.35"
C_DEV = {"local": "#C44E52", "global": "#8172B3"}
TEXT_RC = {"pdf.fonttype": 42, "ps.fonttype": 42, "svg.fonttype": "none",
           "font.family": "sans-serif", "font.sans-serif": ["Arial", "Liberation Sans", "Helvetica", "DejaVu Sans"],
           "font.size": 7, "axes.titlesize": 7, "axes.labelsize": 6.5, "xtick.labelsize": 6, "ytick.labelsize": 6,
           "legend.fontsize": 5.8, "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
           "xtick.major.size": 2.5, "ytick.major.size": 2.5, "xtick.major.pad": 1.5, "ytick.major.pad": 1.5,
           "axes.labelpad": 2}
# ------------------------------------------------------------------------------------


def dense(x):
    return x.toarray() if hasattr(x, "toarray") else np.asarray(x, float)


def load_subject(f):
    """Observed and predicted channel waves (cond x chan x time, µV), source output (cond x src x time)."""
    D = loadmat(f, squeeze_me=True, struct_as_record=False)["DCM"]
    U = dense(D.M.U)                                           # chan x modes
    scale = float(D.xY.scale)
    H = [dense(h) for h in np.atleast_1d(D.H)]
    R = [dense(r) for r in np.atleast_1d(D.R)]
    pred = np.stack([(h @ U.T).T for h in H]) / scale
    obs = np.stack([((h + r) @ U.T).T for h, r in zip(H, R)]) / scale
    J = dense(D.Eg.J).ravel()
    js = np.flatnonzero(J)                                     # states that contribute to the EEG
    ns = len(SRC)
    src = []
    for k in np.atleast_1d(D.K):
        k = dense(k)                                           # time x (states x sources), state-major
        src.append(sum(J[s] * k[:, i * ns:(i + 1) * ns] for i, s in enumerate(js)).T)
    return dict(obs=obs, pred=pred, src=np.stack(src), chans=list(D.xY.name), t=np.asarray(D.xY.pst, float))


def level(X, lv):
    return X[:, LEVELS[lv]].mean(1)


def main():
    subs = [load_subject(f) for f in sorted(FIT_DIR.glob("DCM_sub-*_full.mat"))]
    n = len(subs)
    t = subs[0]["t"]
    chans = subs[0]["chans"]
    obs = np.stack([s["obs"] for s in subs])                   # subj x cond x chan x time
    pred = np.stack([s["pred"] for s in subs])
    src = np.stack([s["src"] for s in subs])                   # subj x cond x src x time

    sns.set_theme(style="ticks", rc=TEXT_RC)
    mm = 1 / 25.4
    fig, axes = plt.subplots(2, 3, figsize=(SIZE_MM[0] * mm, SIZE_MM[1] * mm),
                             gridspec_kw=dict(left=0.075, right=0.985, bottom=0.1, top=0.92, wspace=0.38,
                                              hspace=0.5, width_ratios=[1, 1, 1.1]))
    out = {}

    def band(ax, X, col, ls="-", lw=1.0, lab=None, fill=True):
        m, se = X.mean(0), X.std(0, ddof=1) / np.sqrt(len(X))
        ax.plot(t, m, color=col, ls=ls, lw=lw, label=lab)
        if fill:
            ax.fill_between(t, m - se, m + se, color=col, alpha=0.15, lw=0)
        return m

    for r, (eff, roi, (std, dev), roiname, win) in enumerate(ROWS):
        ci = [chans.index(c) for c in roi]
        O = obs[:, :, ci].mean(2)                              # subj x cond x time
        P = pred[:, :, ci].mean(2)
        # ---- conditions
        ax = axes[r, 0]
        ax.axvspan(*win, color="0.93", lw=0, zorder=0)
        band(ax, level(O, std), C_STD, lab=f"{std} observed")
        band(ax, level(O, dev), C_DEV[eff], lab=f"{dev} observed")
        band(ax, level(P, std), C_STD, ls="--", lw=0.9, lab=f"{std} model", fill=False)
        band(ax, level(P, dev), C_DEV[eff], ls="--", lw=0.9, lab=f"{dev} model", fill=False)
        ax.axhline(0, color="k", lw=0.4)
        ax.set_ylabel("Amplitude (a.u.)")
        ax.set_title(f"{roiname}: {std} vs {dev}", pad=3)
        ax.legend(frameon=False, ncol=2, loc="upper left" if r == 1 else "lower right", handlelength=1.6,
                  columnspacing=0.6, borderaxespad=0.1)
        # ---- difference
        ax = axes[r, 1]
        ax.axvspan(*win, color="0.93", lw=0, zorder=0)
        dO = level(O, dev) - level(O, std)
        dP = level(P, dev) - level(P, std)
        mo = band(ax, dO, "k", lab="observed")
        mp = band(ax, dP, C_DEV[eff], ls="--", lw=1.0, lab="model", fill=False)
        rr = float(np.corrcoef(mo, mp)[0, 1])
        per_sub = [float(np.corrcoef(a, b)[0, 1]) for a, b in zip(dO, dP)]
        ax.axhline(0, color="k", lw=0.4)
        ax.set_ylabel(f"{dev} − {std} (a.u.)")
        ax.set_title(f"Difference wave (group r = {rr:.2f})", pad=3)
        ax.legend(frameon=False, loc="upper left" if r == 1 else "lower right", handlelength=1.6, borderaxespad=0.1)
        # ---- sources
        ax = axes[r, 2]
        ax.axvspan(*win, color="0.93", lw=0, zorder=0)
        dS = level(src, dev) - level(src, std)                  # subj x src x time
        peak = np.abs(dS.mean(0)).max()
        for k, s in enumerate(SRC):
            reg = s[1:]
            ax.plot(t, dS[:, k].mean(0) / peak, color=SRC_COL[reg], lw=1.0, ls="-" if s[0] == "l" else ":",
                    label=f"{'L' if s[0] == 'l' else 'R'} {reg}")
        ax.axhline(0, color="k", lw=0.4)
        ax.set_ylabel("Source output (norm.)")
        ax.set_title(f"{dev} − {std} at each model source", pad=3)
        if r == 1:
            ax.legend(frameon=False, ncol=2, loc="upper right", handlelength=1.6, columnspacing=0.6,
                      borderaxespad=0.1)
        win_idx = (t >= win[0]) & (t <= win[1])
        out[eff] = dict(group_r_difference_wave=rr, per_subject_r_median=float(np.median(per_sub)),
                        per_subject_r_range=[float(min(per_sub)), float(max(per_sub))],
                        source_share_in_window={s: float(np.abs(dS[:, k].mean(0)[win_idx]).mean()
                                                          / np.abs(dS.mean(0)[:, win_idx]).mean(1).sum())
                                                for k, s in enumerate(SRC)})
        for ax in axes[r]:
            ax.axvline(0, color="k", lw=0.5)
            ax.set_xlim(0, 600)
            ax.set_xticks([0, 200, 400, 600])
            sns.despine(ax=ax)
            if r == 1:
                ax.set_xlabel("Time from 5th sound (ms)")
    for k, ax in enumerate(axes.ravel()):
        ax.text(-0.27, 1.12, "ABCDEF"[k], transform=ax.transAxes, fontsize=9, weight="bold", va="top")

    FIG_DIR.mkdir(exist_ok=True)
    fig.savefig(FIG_DIR / "DCM_predicted_ERPs.pdf")
    fig.savefig(FIG_DIR / "DCM_predicted_ERPs.svg")
    svg = FIG_DIR / "DCM_predicted_ERPs.svg"
    svg.write_text(svg.read_text().replace("Liberation Sans", "Arial"))
    fig.savefig(FIG_DIR / "DCM_predicted_ERPs.png", dpi=400)
    (ROOT / "derivatives" / "dcm" / "predicted_erp_fit.json").write_text(json.dumps(out, indent=2))
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
